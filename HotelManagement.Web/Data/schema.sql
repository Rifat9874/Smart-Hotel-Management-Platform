/* =====================================================================
   Rifat Grand Hotel - Hotel Management System
   Database schema (same 11 tables as the original WinForms HMSDB1).

   Safe to run more than once: every table is created only if missing.
   No "GO" needed, so it also works in Somee's "Run scripts" box.
   ===================================================================== */

IF OBJECT_ID(N'dbo.USER_TABLE', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.USER_TABLE (
        NAME          NVARCHAR(50)  NOT NULL,
        PHONE_NUMBER  NVARCHAR(50)  NOT NULL,
        EMAIL         NVARCHAR(50)  NOT NULL,
        PASSWORD      NVARCHAR(MAX) NOT NULL,
        USER_TYPE     NVARCHAR(50)  NOT NULL,
        ADDRESS       NVARCHAR(255) NULL,
        DEPARTMENT    NVARCHAR(100) NULL,
        POSITION      NVARCHAR(100) NULL,
        JOIN_DATE     DATE          NULL,
        CONSTRAINT PK_USER_TABLE PRIMARY KEY (EMAIL)
    );
END;

IF OBJECT_ID(N'dbo.ROOM_TABLE', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.ROOM_TABLE (
        ROOM_ID        NVARCHAR(50)  NOT NULL,
        [TYPE]         NVARCHAR(50)  NOT NULL,
        PPN            INT           NOT NULL,
        [DESCRIPTION]  NVARCHAR(MAX) NULL,
        PICTURE        NVARCHAR(MAX) NULL,
        COMPLIMENTARY  NVARCHAR(MAX) NULL,
        FEATURES       NVARCHAR(MAX) NULL,
        CONSTRAINT PK_ROOM_TABLE PRIMARY KEY (ROOM_ID)
    );
END;

IF OBJECT_ID(N'dbo.ADDITIONAL_PICTURES', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.ADDITIONAL_PICTURES (
        PICTURE_ID  NVARCHAR(50)  NOT NULL,
        ROOM_ID     NVARCHAR(50)  NOT NULL,
        IMAGE_1     NVARCHAR(MAX) NULL,
        IMAGE_2     NVARCHAR(MAX) NULL,
        IMAGE_3     NVARCHAR(MAX) NULL,
        IMAGE_4     NVARCHAR(50)  NULL,
        IMAGE_5     NVARCHAR(50)  NULL,
        CONSTRAINT PK_ADDITIONAL_PICTURES PRIMARY KEY (PICTURE_ID),
        CONSTRAINT FK_ADDITIONAL_PICTURES_ROOM_TABLE FOREIGN KEY (ROOM_ID) REFERENCES dbo.ROOM_TABLE (ROOM_ID)
    );
END;

IF OBJECT_ID(N'dbo.BOOKINGS_TABLE', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.BOOKINGS_TABLE (
        BOOKING_ID      NVARCHAR(50)  NOT NULL,
        EMAIL           NVARCHAR(50)  NOT NULL,
        ROOM_ID         NVARCHAR(50)  NOT NULL,
        CHECK_IN        DATE          NOT NULL,
        CHECK_OUT       DATE          NOT NULL,
        BOOKING_DATE    NVARCHAR(50)  NOT NULL,
        BOOKING_STATUS  NVARCHAR(50)  NOT NULL,
        TOTAL_AMOUNT    DECIMAL(10,2) NULL,
        CONSTRAINT PK_BOOKINGS_TABLE PRIMARY KEY (BOOKING_ID),
        CONSTRAINT FK_BOOKINGS_TABLE_USER_TABLE FOREIGN KEY (EMAIL)   REFERENCES dbo.USER_TABLE (EMAIL),
        CONSTRAINT FK_BOOKINGS_TABLE_ROOM_TABLE FOREIGN KEY (ROOM_ID) REFERENCES dbo.ROOM_TABLE (ROOM_ID)
    );
END;

IF OBJECT_ID(N'dbo.PAYMENT', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.PAYMENT (
        P_ID         NVARCHAR(50) NOT NULL,
        BOOKING_ID   NVARCHAR(50) NOT NULL,
        CARD_NUMBER  NVARCHAR(50) NOT NULL,
        EXP_DATE     DATE         NOT NULL,
        CODE         NVARCHAR(50) NOT NULL,
        BILL         INT          NOT NULL,
        CONSTRAINT PK_PAYMENT PRIMARY KEY (P_ID),
        CONSTRAINT FK_PAYMENT_BOOKINGS_TABLE FOREIGN KEY (BOOKING_ID) REFERENCES dbo.BOOKINGS_TABLE (BOOKING_ID)
    );
END;

IF OBJECT_ID(N'dbo.REVIEWS_TABLE', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.REVIEWS_TABLE (
        REVIEW_ID    INT IDENTITY(1,1) NOT NULL,
        BOOKING_ID   NVARCHAR(50)  NOT NULL,
        EMAIL        NVARCHAR(50)  NOT NULL,
        RATING       INT           NOT NULL,
        COMMENTS     NVARCHAR(MAX) NULL,
        REVIEW_DATE  DATETIME      NULL,
        CONSTRAINT PK_REVIEWS_TABLE PRIMARY KEY (REVIEW_ID),
        CONSTRAINT FK_REVIEWS_TABLE_BOOKINGS_TABLE FOREIGN KEY (BOOKING_ID) REFERENCES dbo.BOOKINGS_TABLE (BOOKING_ID),
        CONSTRAINT FK_REVIEWS_TABLE_USER_TABLE     FOREIGN KEY (EMAIL)      REFERENCES dbo.USER_TABLE (EMAIL)
    );
END;

IF OBJECT_ID(N'dbo.ROOM_ASSIGNMENTS', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.ROOM_ASSIGNMENTS (
        ASSIGNMENT_ID  NVARCHAR(50) NOT NULL,
        ROOM_ID        NVARCHAR(50) NOT NULL,
        ASSIGNED_DATE  DATE         NOT NULL,
        EMAIL          NVARCHAR(50) NOT NULL,
        ROOM_STATUS    NVARCHAR(50) NOT NULL,
        CONSTRAINT PK_ROOM_ASSIGNMENTS PRIMARY KEY (ASSIGNMENT_ID),
        CONSTRAINT FK_ROOM_ASSIGNMENTS_ROOM_TABLE FOREIGN KEY (ROOM_ID) REFERENCES dbo.ROOM_TABLE (ROOM_ID),
        CONSTRAINT FK_ROOM_ASSIGNMENTS_USER_TABLE FOREIGN KEY (EMAIL)   REFERENCES dbo.USER_TABLE (EMAIL)
    );
END;

IF OBJECT_ID(N'dbo.MaintenanceRequests', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.MaintenanceRequests (
        M_ID         NVARCHAR(50) NOT NULL,
        ROOM_ID      NVARCHAR(50) NOT NULL,
        PROBLEM      NVARCHAR(50) NOT NULL,
        STATUS       NVARCHAR(50) NOT NULL,
        SUBMIT_DATE  NVARCHAR(50) NOT NULL,
        EMAIL        NVARCHAR(50) NOT NULL,
        CONSTRAINT PK_MaintenanceRequests PRIMARY KEY (M_ID),
        CONSTRAINT FK_MaintenanceRequests_ROOM_TABLE FOREIGN KEY (ROOM_ID) REFERENCES dbo.ROOM_TABLE (ROOM_ID),
        CONSTRAINT FK_MaintenanceRequests_USER_TABLE FOREIGN KEY (EMAIL)   REFERENCES dbo.USER_TABLE (EMAIL)
    );
END;

IF OBJECT_ID(N'dbo.LEAVE_REQUEST', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.LEAVE_REQUEST (
        LEAVE_ID   NVARCHAR(50) NOT NULL,
        EMAIL      NVARCHAR(50) NOT NULL,
        FROM_DATE  NVARCHAR(50) NOT NULL,
        TO_DATE    NVARCHAR(50) NOT NULL,
        REASON     NVARCHAR(50) NOT NULL,
        STATUS     NVARCHAR(50) NOT NULL,
        CONSTRAINT PK_LEAVE_REQUEST PRIMARY KEY (LEAVE_ID),
        CONSTRAINT FK_LEAVE_REQUEST_USER_TABLE FOREIGN KEY (EMAIL) REFERENCES dbo.USER_TABLE (EMAIL)
    );
END;

IF OBJECT_ID(N'dbo.FACILITIES_BOOKING', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.FACILITIES_BOOKING (
        FACILITY_BOOKING_ID  INT IDENTITY(1,1) NOT NULL,
        EMAIL                NVARCHAR(50)  NOT NULL,
        FACILITY_NAME        NVARCHAR(100) NOT NULL,
        BOOKING_DATE         DATETIME      NOT NULL,
        GUESTS_COUNT         INT           NOT NULL,
        TOTAL_PRICE          DECIMAL(10,2) NOT NULL,
        BOOKING_STATUS       NVARCHAR(20)  NULL,
        BOOKING_TIME         DATETIME      NULL CONSTRAINT DF_FACILITIES_BOOKING_TIME DEFAULT (GETDATE()),
        CONSTRAINT PK_FACILITIES_BOOKING PRIMARY KEY (FACILITY_BOOKING_ID),
        CONSTRAINT FK_FACILITIES_EMAIL FOREIGN KEY (EMAIL) REFERENCES dbo.USER_TABLE (EMAIL)
    );
END;

IF OBJECT_ID(N'dbo.EMPLOYEE_SALARY', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.EMPLOYEE_SALARY (
        SALARY_ID       INT IDENTITY(1,1) NOT NULL,
        EMPLOYEE_EMAIL  NVARCHAR(50)  NOT NULL,
        SALARY_AMOUNT   DECIMAL(10,2) NOT NULL,
        PAYMENT_DATE    DATE          NOT NULL,
        PAYMENT_METHOD  NVARCHAR(50)  NULL,
        ALLOWANCES      DECIMAL(10,2) NULL,
        DEDUCTIONS      DECIMAL(10,2) NULL,
        BONUS_AMOUNT    DECIMAL(10,2) NULL,
        BONUS_REASON    NVARCHAR(100) NULL,
        CONSTRAINT PK_EMPLOYEE_SALARY PRIMARY KEY (SALARY_ID),
        CONSTRAINT FK_EMPLOYEE_SALARY_USER_TABLE FOREIGN KEY (EMPLOYEE_EMAIL) REFERENCES dbo.USER_TABLE (EMAIL)
    );
END;
